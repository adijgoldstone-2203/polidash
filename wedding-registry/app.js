// ==========================================
// 3. DATABASE CLIENT STATE & SYNC ENGINE
// ==========================================
let dbProvider = 'local';
let supabaseClient = null;
let firestoreDb = null;

// Initialize clients based on config
function initDatabase() {
  const statusEl = document.getElementById('sync-status');
  const statusTextEl = document.getElementById('sync-status-text');

  if (DATABASE_CONFIG.provider === 'supabase' && DATABASE_CONFIG.supabase.url && DATABASE_CONFIG.supabase.anonKey) {
    try {
      supabaseClient = supabase.createClient(DATABASE_CONFIG.supabase.url, DATABASE_CONFIG.supabase.anonKey);
      dbProvider = 'supabase';
      console.log("Supabase client initialized successfully.");
      
      // Update badge
      statusEl.classList.remove('hidden');
      statusEl.classList.add('flex');
      statusEl.className = statusEl.className.replace(/bg-\w+-\d+/g, 'bg-emerald-50').replace(/text-\w+-\d+/g, 'text-emerald-800').replace(/border-\w+-\d+/g, 'border-emerald-100');
      statusTextEl.innerText = "Live Realtime Sync (Supabase)";
      
      setupSupabaseSync();
      return;
    } catch (e) {
      console.error("Failed to initialize Supabase, fallback to localStorage:", e);
    }
  } else if (DATABASE_CONFIG.provider === 'firebase' && DATABASE_CONFIG.firebase.projectId) {
    try {
      firebase.initializeApp(DATABASE_CONFIG.firebase);
      firestoreDb = firebase.firestore();
      dbProvider = 'firebase';
      console.log("Firebase Firestore initialized successfully.");

      // Update badge
      statusEl.classList.remove('hidden');
      statusEl.classList.add('flex');
      statusEl.className = statusEl.className.replace(/bg-\w+-\d+/g, 'bg-emerald-50').replace(/text-\w+-\d+/g, 'text-emerald-800').replace(/border-\w+-\d+/g, 'border-emerald-100');
      statusTextEl.innerText = "Live Realtime Sync (Firebase)";

      setupFirebaseSync();
      return;
    } catch (e) {
      console.error("Failed to initialize Firebase, fallback to localStorage:", e);
    }
  }

  // Fallback / Default Local Sync
  dbProvider = 'local';
  console.log("Using Local Storage Sync.");
  statusEl.classList.remove('hidden');
  statusEl.classList.add('flex');
  statusEl.className = statusEl.className.replace(/bg-\w+-\d+/g, 'bg-plum/5').replace(/text-\w+-\d+/g, 'text-plum/80').replace(/border-\w+-\d+/g, 'border-plum/20');
  statusTextEl.innerText = "Demo Mode (Local Storage)";
  setupLocalSync();
}

// -- Supabase Realtime synchronization
function setupSupabaseSync() {
  if (!supabaseClient) return;

  // 1. Initial Load
  supabaseClient
    .from(DATABASE_CONFIG.supabase.table)
    .select('item_id, claimed')
    .then(({ data, error }) => {
      if (error) {
        console.error("Error loading registry items from Supabase:", error);
        return;
      }
      if (data) {
        data.forEach(row => {
          const item = registryItems.find(i => i.id === row.item_id);
          if (item) {
            item.claimed = row.claimed;
          }
        });
        renderGrid();
      }
    });

  // 2. Realtime Channel Subscription
  supabaseClient
    .channel('public:registry_claims')
    .on('postgres_changes', { event: '*', schema: 'public', table: DATABASE_CONFIG.supabase.table }, payload => {
      const updatedRow = payload.new;
      if (updatedRow && updatedRow.item_id !== undefined) {
        const item = registryItems.find(i => i.id === updatedRow.item_id);
        if (item) {
          item.claimed = updatedRow.claimed;
          renderGrid();
        }
      }
    })
    .subscribe();
}

// -- Firebase Realtime synchronization
function setupFirebaseSync() {
  if (!firestoreDb) return;

  firestoreDb.collection('registry_claims')
    .onSnapshot(snapshot => {
      snapshot.docChanges().forEach(change => {
        const docData = change.doc.data();
        const itemId = parseInt(change.doc.id, 10);
        const item = registryItems.find(i => i.id === itemId);
        if (item) {
          item.claimed = docData.claimed;
        }
      });
      renderGrid();
    }, error => {
      console.error("Error subscribing to Firebase:", error);
    });
}

// -- Local Storage Sync
function setupLocalSync() {
  loadLocalClaims();

  // Handle storage updates in separate browser tabs
  window.addEventListener('storage', (event) => {
    if (event.key === 'registry_claims') {
      loadLocalClaims();
    }
  });
}

function loadLocalClaims() {
  const savedClaims = localStorage.getItem('registry_claims');
  if (savedClaims) {
    try {
      const claims = JSON.parse(savedClaims);
      // Reset items in list to false first
      registryItems.forEach(i => i.claimed = false);
      // Set true for claimed items
      Object.keys(claims).forEach(idStr => {
        const itemId = parseInt(idStr, 10);
        const item = registryItems.find(i => i.id === itemId);
        if (item && claims[idStr].claimed) {
          item.claimed = true;
        }
      });
    } catch (e) {
      console.error("Error parsing local storage claims:", e);
    }
  }
  renderGrid();
}

