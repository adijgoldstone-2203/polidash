// 5. INTERACTIVE MODAL & CLAIMS WORKFLOW
// ==========================================
const claimModal = document.getElementById('claim-modal');
const successModal = document.getElementById('success-modal');
const claimForm = document.getElementById('claim-form');

const claimItemIdInput = document.getElementById('claim-item-id');
const claimItemTitleText = document.getElementById('claim-item-title');
const claimItemPriceText = document.getElementById('claim-item-price');

let activeClaimItemId = null;

function openClaimModal(itemId) {
  const item = registryItems.find(i => i.id === itemId);
  if (!item || item.claimed) return;
  
  activeClaimItemId = itemId;
  claimItemIdInput.value = itemId;
  claimItemTitleText.innerText = item.title;
  
  const formattedPrice = new Intl.NumberFormat('he-IL', { style: 'currency', currency: 'ILS', maximumFractionDigits: 0 }).format(item.price);
  claimItemPriceText.innerText = formattedPrice;
  
  // Show Modal with smooth animation
  claimModal.classList.add('modal-open');
  document.body.classList.add('overflow-hidden');
  
  // Focus name field
  setTimeout(() => {
    document.getElementById('claim-name').focus();
  }, 100);
}

function closeClaimModal() {
  claimModal.classList.remove('modal-open');
  document.body.classList.remove('overflow-hidden');
  claimForm.reset();
  activeClaimItemId = null;
}

// Handle Form Submission -> Set claimed true -> DB update -> Open Success
async function handleClaimSubmit(event) {
  event.preventDefault();
  
  const itemId = parseInt(claimItemIdInput.value, 10);
  const name = document.getElementById('claim-name').value.trim();
  const email = document.getElementById('claim-email').value.trim();
  
  if (!itemId || !name || !email) return;
  
  // 1. Toggle claimed property inside local array immediately
  const item = registryItems.find(i => i.id === itemId);
  if (item) {
    item.claimed = true;
  }
  
  // 2. Close Form Modal
  claimModal.classList.remove('modal-open');
  
  // 3. Open Success Modal Overlay
  successModal.classList.add('modal-open');
  
  // 4. Sync to DB asynchronously
  syncClaimToBackend(itemId, name, email);
}

// Persistence synchronization logic
async function syncClaimToBackend(itemId, name, email) {
  if (dbProvider === 'supabase' && supabaseClient) {
    try {
      const { error } = await supabaseClient
        .from(DATABASE_CONFIG.supabase.table)
        .upsert({ 
          item_id: itemId, 
          claimed: true, 
          claimer_name: name, 
          claimer_email: email 
        }, { onConflict: 'item_id' });
        
      if (error) throw error;
      console.log(`Successfully synced claim for item ${itemId} to Supabase`);
    } catch (e) {
      console.error("Failed to sync claim to Supabase, writing to localStorage fallback:", e);
      writeToLocalStorage(itemId, name, email);
    }
  } else if (dbProvider === 'firebase' && firestoreDb) {
    try {
      await firestoreDb.collection('registry_claims').doc(String(itemId)).set({
        claimed: true,
        claimer_name: name,
        claimer_email: email,
        claimed_at: firebase.firestore.FieldValue.serverTimestamp()
      });
      console.log(`Successfully synced claim for item ${itemId} to Firebase`);
    } catch (e) {
      console.error("Failed to sync claim to Firebase, writing to localStorage fallback:", e);
      writeToLocalStorage(itemId, name, email);
    }
  } else {
    // Fallback or explicit local storage choice
    writeToLocalStorage(itemId, name, email);
    console.log(`Saved claim for item ${itemId} locally.`);
  }
}

function writeToLocalStorage(itemId, name, email) {
  let claims = {};
  const savedClaims = localStorage.getItem('registry_claims');
  if (savedClaims) {
    try { claims = JSON.parse(savedClaims); } catch(e) {}
  }
  claims[itemId] = { 
    claimed: true, 
    name, 
    email, 
    claimed_at: new Date().toISOString() 
  };
  localStorage.setItem('registry_claims', JSON.stringify(claims));
  // Dispatch custom storage event for sync in local tab
  window.dispatchEvent(new Event('storage'));
}

function closeSuccessModal() {
  successModal.classList.remove('modal-open');
  document.body.classList.remove('overflow-hidden');
  
  // Refreshes the product grid instantly
  renderGrid();
}

// Expose functions globally to HTML handlers
window.openClaimModal = openClaimModal;
window.closeClaimModal = closeClaimModal;
window.closeSuccessModal = closeSuccessModal;

// Initialize on DOM Load
document.addEventListener('DOMContentLoaded', () => {
  initDatabase();
  
  // Event listeners
  document.getElementById('close-claim-modal').addEventListener('click', closeClaimModal);
  document.getElementById('cancel-claim-modal').addEventListener('click', closeClaimModal);
  document.getElementById('claim-form').addEventListener('submit', handleClaimSubmit);
  
  document.getElementById('place-order-btn').addEventListener('click', closeSuccessModal);
  
  // Close modals when clicking outside the container
  claimModal.addEventListener('click', (e) => {
    if (e.target === claimModal) closeClaimModal();
  });
  successModal.addEventListener('click', (e) => {
    if (e.target === successModal) closeSuccessModal();
  });
});
